#!/bin/bash
# Generates pipeline/PIPELINE.md: which file is authoritative for each step.
#
# WHY: the repository holds 56 step*.R scripts and nothing said which one runs.
#
# PRINCIPLE: this script DERIVES, it does not invent. It reads the launchers and
# extracts what they actually execute. When no launcher references a
# script, it writes "NO LAUNCHER FOUND" -- the most
# useful information in the file, not a gap to fill by judgement.
#
# Modifies NOTHING. Read-only, except PIPELINE.md.
set -uo pipefail

ROOT="${ROOT:-${DFP_REPO:?set DFP_REPO}}"
V6="$ROOT/pipeline"
HOMEDIR="${HOMEDIR:-$HOME}"
OUT="${OUT:-$V6/PIPELINE.md}"

[ -d "$V6" ] || { echo "ABORT: $V6 not found" >&2; exit 1; }

LINKS=$(mktemp)
trap 'rm -f "$LINKS"' EXIT

# --- 1. inventory of launchers: R_script <TAB> launcher <TAB> raw target ---
scanner() {
  local f="$1" base cd_dir
  base=$(dirname "$f")
  cd_dir=$(grep -hoE '^[[:space:]]*cd[[:space:]]+"?[^"]+"?' "$f" 2>/dev/null | tail -1            | sed -E 's/^[[:space:]]*cd[[:space:]]+//; s/"//g')
  cd_dir=$(eval echo "$cd_dir" 2>/dev/null)

  # Pass 1: `Rscript <file>` -- the direct invocation.
  # sed removes commented lines: a `# Rscript old.R` is not a launcher,
  # and without this filter make_manifest.sh would declare itself the launcher of step7
  # (its comment on pass 2 quotes the call as an example).
  sed 's/^[[:space:]]*#.*$//' "$f" 2>/dev/null   | grep -hoE 'Rscript[[:space:]]+[^[:space:];|&]+' | while read -r line; do
    target=${line#Rscript}
    target=$(printf '%s' "$target" | tr -d " \"'")
    # -e, --vanilla, - : inline code, no file designated HERE (see pass 2)
    case "$target" in -*|'') continue ;; esac
    emit "$f" "$base" "$cd_dir" "$target"
  done

  # Pass 2: `source('<file>.R')` inside an `Rscript -e "..."` block.
  # This is the form used by step7_export_jtrawl_grit.sh l. 78-81:
  #     Rscript --vanilla -e "
  #       .libPaths('~/R/library')
  #       source('step7_export_jtrawl.R')
  #     "
  # Pass 1 misses it by construction (-e = inline code), and step7 would be
  # reported NO LAUNCHER FOUND although it runs. Only
  # .sh/.sbatch are scanned: a source() found here is indeed a launcher invocation,
  # not an internal call between R scripts.
  sed 's/^[[:space:]]*#.*$//' "$f" 2>/dev/null   | grep -hoE "source\([\"']([^\"']+)\.[Rr][\"']\)" | while read -r line; do
    target=$(printf '%s' "$line" | sed -E "s/^source\([\"']//; s/[\"']\)$//")
    [ -z "$target" ] && continue
    emit "$f" "$base" "$cd_dir" "$target"
  done
}

# Resolution of a target against the four plausible roots, then output
# of a line `R_script <TAB> launcher <TAB> raw target`. Shared by both
# passes of scanner().
emit() {
  local f="$1" base="$2" cd_dir="$3" target="$4" resolved="" cand
  # A relative target is resolved against the launcher's `cd`, as the
  # shell would do -- NEVER against the generator's current directory.
  # Without `cd`, the directory is the submission one,
  # unknown: we try the launcher's folder, then pipeline.
  # R and the shell both expand a leading `~/`: we do the same.
  case "$target" in "~/"*) target="$HOMEDIR/${target#"~/"}" ;; esac
  case "$target" in
    /*) set -- "$target" ;;
    *)  if [ -n "$cd_dir" ]; then set -- "$cd_dir/$target"
        else set -- "$base/$target" "$V6/$target"; fi ;;
  esac
  for cand in "$@"; do
    if [ -f "$cand" ]; then resolved=$(readlink -f "$cand"); break; fi
  done
  # Rscript "$S": the target is a variable, undecidable without executing
  if [ -z "$resolved" ] && case "$target" in *'$'*) true ;; *) false ;; esac; then
    resolved="VARIABLE:$target"
  fi
  printf '%s	%s	%s
' "${resolved:-UNRESOLVED:$target}" "${f#$HOMEDIR/}" "$target"
}

# The *.sh of the repository count as much as the *.sbatch: step7 is submitted
# by `sbatch step7_export_jtrawl_grit.sh`, which lives in pipeline/. Omitting them
# would report NO LAUNCHER FOUND on a step that runs -- a manifest that
# lies is worse than no manifest.
{ find "$ROOT" \( -name '*.sbatch' -o -name '*.sh' \) 2>/dev/null
  ls "$HOMEDIR"/*.sbatch "$HOMEDIR"/*.sh 2>/dev/null
} | sort -u | grep -vE '/(make_manifest|check_pipeline|ranger_pipeline|rapatrier_step1)[.]sh$' | while IFS= read -r f; do scanner "$f"; done > "$LINKS"

launchers_of() { awk -F'\t' -v c="$1" '$1==c {print $2}' "$LINKS" | sort -u | paste -sd',' - | sed 's/,/, /g'; }
sheet() { printf '`%s` · %s o · %s' "$(md5sum "$1" | cut -c1-8)" \
                 "$(stat -c%s "$1")" "$(stat -c%y "$1" | cut -c1-10)"; }

# --- 2. the document ---------------------------------------------------------
COMMIT=$(cd "$ROOT" && git rev-parse --short HEAD 2>/dev/null || echo "not in git")
DIRTY=$(cd "$ROOT" && git status --porcelain pipeline 2>/dev/null | wc -l)

{
echo "# Which file is authoritative — Dredging Footprint pipeline"
echo
echo "**Generated by \`make_manifest.sh\` on $(date '+%Y-%m-%d %H:%M') — commit \`$COMMIT\`.**"
echo "Do not edit by hand: any change will be overwritten at the next generation."
echo "The guard is \`check_pipeline.sh\`."
echo
if [ "$DIRTY" -gt 0 ]; then
  echo "> ⚠️ **$DIRTY file(s) of \`pipeline/\` are not committed.** The fingerprints"
  echo "> below describe the disk, not commit \`$COMMIT\`. As long as this is the case,"
  echo "> git cannot tell which version ran."
  echo
fi
echo "## Run from a copy OUTSIDE the repository"
echo
echo "A repository launcher that does \`cd\` elsewhere then \`source('x.R')\` runs the copy"
echo "from that elsewhere, not the repository one. The repository file then has the same name"
echo "without being what ran. This is worse than a step without a launcher: it reads as"
echo "traceable when it is not."
echo
OUTSIDE=$(awk -F'	' -v r="$ROOT/" '$1 !~ /^(UNRESOLVED|VARIABLE):/ && index($1, r) != 1 {print "| `" $2 "` | `" $1 "` |"}' "$LINKS" | sort -u)
if [ -n "$OUTSIDE" ]; then
  echo "| launcher | file actually executed |"
  echo "|---|---|"
  echo "$OUTSIDE"
else
  echo "None: all launchers examined execute repository files."
fi
echo

echo "## By step"
echo
echo "\"NO LAUNCHER FOUND\" means that no \`.sbatch\` or \`.sh\` examined cites this"
echo "file. It is not a failure of the script: it is the real state of the repository."
echo
echo "| step | file | fingerprint · size · date | run by |"
echo "|---|---|---|---|"

for n in 0 1 2 3 4 5 6 7; do
  found=0
  while IFS= read -r c; do
    [ -n "$c" ] || continue
    found=1
    l=$(launchers_of "$c")
    printf '| step%s | `%s` | %s | %s |\n' "$n" "${c#$V6/}" "$(sheet "$c")" \
           "${l:-**NO LAUNCHER FOUND**}"
  done < <(find "$V6" -maxdepth 2 -name "step${n}*.R" \
           -not -path '*/preuves/*' -not -path '*/scripts_principaux/*' 2>/dev/null | sort)
  [ "$found" -eq 0 ] && printf '| step%s | — | — | *no script found* |\n' "$n"
done

echo
echo "## What each launcher executes"
echo
echo "Extracted from the \`Rscript <file>\` found in the \`.sbatch\` of the repository and the"
echo "\`.sh\`/\`.sbatch\` of \`\$HOME\`, plus the \`source('x.R')\` placed in yr
\`Rscript -e\` block. Code actually written inline in a \`-e\` (without source)"
echo "designates no file and is omitted."
echo
echo "| launcher | executes | resolved? |"
echo "|---|---|---|"
sort -t"$(printf '\t')" -k2,2 "$LINKS" | while IFS=$'\t' read -r resolved launcher raw; do
  case "$resolved" in
    UNRESOLVED:*) printf '| `%s` | `%s` | ❌ **not found** |\n' "$launcher" "$raw" ;;
    VARIABLE:*)   printf '| `%s` | `%s` | ⬜ variable, not resolvable without executing |\n' "$launcher" "$raw" ;;
    *)            printf '| `%s` | `%s` | ✅ |\n' "$launcher" "${resolved#$HOMEDIR/}" ;;
  esac
done

echo
echo "## Variants kept on purpose"
echo
echo "They are **not** clutter: they are evidence. Their reason for being is written"
echo "in the two notes below, which remain the source — this manifest points to them rather"
echo "than copying them, so as not to diverge from them."
echo
echo "- \`WHICH_WORKER.md\` — which step5 worker to run, and why the other is kept"
echo "  (validation reference, with proof of equivalence)."
echo "- \`step2_PROVENANCE.md\` — which version of step2 produced which run."
echo
echo "## What this file does not say"
echo
echo "- It does not say whether a script is **correct**, only which one is **executed**."
echo "- It does not trace history: to know which job produced yr output, read the"
echo "  job log, which names its output file."
echo "- It does not cover the \`.sh\` of \`\$HOME\` as objects to tidy: they are read to"
echo "  trace the launchers, never modified."
} > "$OUT"

echo "written: $OUT"
echo "  'NO LAUNCHER FOUND' lines: $(grep -c 'NO LAUNCHER FOUND' "$OUT")"
echo "  launchers not found            : $(grep -c '[*][*]not found[*][*]' "$OUT")"
